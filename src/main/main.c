void initializeHeap(void)
{
	unsigned long heap;
	unsigned long size;

	heap = (_end & 0xfffffff0) + 0x10;
	size = ((_stack_addr - (_stack_size << 10)) & 0xfffffff0) - heap;
	InitHeap3((unsigned long *)heap, size);
}

