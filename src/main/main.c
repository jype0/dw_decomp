		GsSetWorkBase(&GS_WORK_BASES[ACTIVE_FRAMEBUFFER * 0x14000]);
		GsClearOt(0, 0, ACTIVE_ORDERING_TABLE);
		processInput();
		tickTextboxes(1);

		if (readPStat(PSTAT_TEXT_ARG_1) == 0) {
			done = newGameStateMachine();
		}

		tickObjects();
		renderObjects();
		applyHUDOffset(ACTIVE_FRAMEBUFFER);
		DrawSync(0);
		VSync(3);
