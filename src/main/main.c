void MAIN_func_800F179C(void *model, int32_t compIdx, int32_t color)
{
  char *p;
  int32_t new_var;
  int32_t new_var2;
  char *comp;
  int32_t i;
  int32_t attr;
  int new_var3;
  comp = (char *) model;
  comp = comp + 0xc;
  comp = comp + (compIdx * 0x1c);
  new_var = *((int32_t *) (comp + 0x14));
  new_var3 = 0x10;
  p = *((char **) (comp + new_var3));
  for (i = 0; i < new_var; i++)
  {
    attr = ((*((int32_t *) p)) >> 0x18) & 0xff;
    if (attr & 4)
    {
      attr = ((*((int32_t *) p)) >> 0x18) & 0xff;
      *((int16_t *) (p + 6)) = (int16_t) color;
      new_var2 = attr;
      if (new_var2 & 8)
      {
        if (!(attr & new_var3))
        {
          p += 0x20;
        }
        else
        {
          p += 0x2c;
        }
      }
      else
        if (!(attr & new_var3))
      {
        p += 0x1c;
      }
      else
      {
        p += 0x24;
      }
    }
  }

}

