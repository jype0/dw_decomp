char *_strncpy(char *dst, char *src, int32_t n)
{
	char c;
	int32_t i;

	i = 0;
	while (i < n) {
		c = *src;
		if (c == 0) {
			break;
		}

		src++;
		*dst++ = c;
		i++;
	}

	return dst;
}

int32_t createByteSum(uint8_t *data, int32_t len)
{
	uint32_t sum;
	int32_t i;

	sum = 0;
	for (i = 0; i < len; i++) {
		sum += *data++;
	}
	return sum;
}

