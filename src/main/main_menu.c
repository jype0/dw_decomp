/*
 * Moves the cursor with up and down, from pad 1 (which bit 0) and pad 2
 * (bit 1). Returns 1 for cross, 2 for triangle and 0 otherwise.
 */
int32_t tickMenuCursor(MenuCursor *cursor, int32_t which)
{
	int32_t input;
	int32_t lo;
	int32_t hi;

	lo = CHANGED_INPUT & 0xFFFF;
	hi = (uint32_t)(CHANGED_INPUT & 0xFFFF0000) >> 0x10;
	input = 0;
	if (which & 1) {
		input |= lo;
	}
	if (which & 2) {
		input |= hi;
	}
	if (input == 0x1000) {
		if (0 < cursor->pos) {
			playSound(0, 2);
			cursor->pos--;
		} else if (0 < cursor->scroll) {
			playSound(0, 2);
			cursor->scroll--;
		}
	}
	if (input == 0x4000) {
		if (cursor->pos < cursor->count - 1) {
			playSound(0, 2);
			cursor->pos++;
		} else if (cursor->scroll < cursor->max) {
			playSound(0, 2);
			cursor->scroll++;
		}
	}
	if (input == 0x10) {
		playSound(0, 4);
		return 2;
	}
	if (input == 0x40) {
		playSound(0, 3);
		return 1;
	}
	return 0;
}

