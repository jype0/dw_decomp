void VS_tickVersusIntro(void)
{
	switch (VS_STATE_STATE) {
	case 0:
		MAIN_D_8013525E++;
		if (MAIN_D_8013525E == 10) {
			VS_STATE_STATE++;
		}
		break;
	case 1:
		MAIN_D_8013525C++;
		if (MAIN_D_8013525C == 20) {
			VS_STATE_STATE++;
			MAIN_D_80135262 = 1;
		}
		break;
	case 2:
		MAIN_D_8013525E--;
		if (MAIN_D_8013525E == 0) {
			VS_STATE_STATE++;
			MAIN_D_8013525C = 0;
		}
		break;
	case 3:
		MAIN_D_8013525C++;
		if (MAIN_D_8013525C == 10) {
			VS_STATE_STATE++;
		}
		break;
	case 4:
		MAIN_D_80135261++;
		if (MAIN_D_80135261 == VS_D_800716A8[11]) {
			VS_STATE_STATE++;
		} else {
			VS_STATE_STATE = 0;
			MAIN_D_8013525C = 0;
		}
		break;
	case 5:
		MAIN_D_8013525C++;
		if (MAIN_D_8013525C == 0x50) {
			MAIN_D_80135262 = 1;
		}
		break;
	}
}

