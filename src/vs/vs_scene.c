void VS_initializeVS(void)
{
	int16_t result;

	VS_resetMatchState();
	VS_loadVSAssets(VS_D_800716A8[10]);
	VS_addInputObjects();
	VS_CURRENT_BATTLE = -1;
	VS_playVersusIntroSequence();
	VS_CURRENT_BATTLE = 0;
	while (VS_CURRENT_BATTLE < VS_D_800716A8[11]) {
#if !defined(VERSION_JP)
		PLAYTIME_FRAMES = 0;
#endif
		VS_loadFighterEntities(VS_CURRENT_BATTLE);
		ENTITY_TABLE[1]->isOnScreen = 1;
		ENTITY_TABLE[2]->isOnScreen = 1;
		VSLoadSounds();
#if !defined(VERSION_JP)
		((DigimonEntity *)ENTITY_TABLE[1])->stats.current.vabId = 4;
		((DigimonEntity *)ENTITY_TABLE[2])->stats.current.vabId = 5;
#endif
		loadDigimonSounds(4, ENTITY_TABLE[1]->type);
		loadDigimonSounds(5, ENTITY_TABLE[2]->type);
		VS_setVSPhase(0xa);
		VS_addArenaRenderers();
		VS__runIntro(VS_D_800716A8[10]);
		VS_CAMERA_STATE = 1;
		result = VS__combatMain();
		VS_removeCameraIntro();
		VS_removeVSPhase();
		VS_removeArenaRenderers();
		if (result == 1) {
			VS_D_80071690[0][VS_CURRENT_BATTLE] = 1;
			VS_D_8007169C[1][VS_CURRENT_BATTLE] = 1;
			VS_STATE_WINS[0]++;
			VS_STATE_LOSSES[1]++;
		}
		if (result == -1) {
			VS_D_80071690[1][VS_CURRENT_BATTLE] = 1;
			VS_D_8007169C[0][VS_CURRENT_BATTLE] = 1;
			VS_STATE_WINS[1]++;
			VS_STATE_LOSSES[0]++;
		}
		if (result == 2) {
			VS_D_8007169C[0][VS_CURRENT_BATTLE] = 1;
			VS_D_8007169C[1][VS_CURRENT_BATTLE] = 1;
			VS_STATE_LOSSES[0]++;
			VS_STATE_LOSSES[1]++;
		}
		ENTITY_TABLE[1]->isOnScreen = 0;
		ENTITY_TABLE[2]->isOnScreen = 0;
		VS_playVersusIntroSequence();
		VS_CURRENT_BATTLE++;
	}

	VS_unloadFighterEntities();
}

